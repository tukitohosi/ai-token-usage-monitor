#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum UsageSource {
    TotalDelta,
    TotalSegmentStart,
    LastFallback,
}

impl UsageSource {
    pub(crate) fn as_str(self) -> &'static str {
        match self {
            Self::TotalDelta => "total-delta",
            Self::TotalSegmentStart => "total-segment-start",
            Self::LastFallback => "last-fallback",
        }
    }
}

#[derive(Clone, Debug)]
pub(crate) struct PendingUsageEvent {
    pub logical_key: Vec<u8>,
    pub source_ordinal: Option<i64>,
    pub source_line: i64,
    pub end_offset: i64,
    pub occurred_at_ms: Option<i64>,
    pub source: UsageSource,
    pub attribution: Attribution,
    pub usage: TokenUsage,
    pub cache_metrics_available: bool,
    pub request_input_tokens: Option<i64>,
    pub payload_hash: Vec<u8>,
}

#[derive(Clone, Debug)]
pub(crate) struct ParseEffects {
    pub event: Option<PendingUsageEvent>,
    pub warning_codes: Vec<&'static str>,
}

impl ParseEffects {
    pub(crate) fn empty() -> Self {
        Self {
            event: None,
            warning_codes: Vec::new(),
        }
    }
}
