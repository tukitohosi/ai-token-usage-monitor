/// One locally derived, canonical usage event. `task_key` is an irreversible
/// hash generated by the index; no rollout id, path, prompt, response, or
/// conversation title is exposed.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct LocalUsageEvent {
    pub task_key: String,
    pub occurred_at_ms: Option<i64>,
    /// A Work counter can be located within a day, but has no per-call timestamp.
    pub day_only: bool,
    #[serde(skip)]
    pub request_input_tokens: Option<i64>,
    pub model_label: String,
    pub project_label: String,
    pub usage: TokenUsage,
    /// True only when this source supplied the cache components needed for a
    /// cache-hit calculation. It never exposes the raw source record.
    pub cache_metrics_available: bool,
}

